def seed_questions() -> None:
    db = SessionLocal()
    try:
        if db.query(Question).count() > 0:
            return
        for subject, grade, content, answer, explanation, options in QUESTIONS:
            db.add(
                Question(
                    subject=subject,
                    grade=grade,
                    content=content,
                    answer=answer,
                    explanation=explanation,
                    options=json.dumps(options, ensure_ascii=False),
                )
            )
        db.commit()
        print(f"[seed] {len(QUESTIONS)} questions ready")
    finally:
        db.close()
