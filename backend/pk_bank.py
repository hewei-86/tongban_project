def seed_questions() -> None:
    db = SessionLocal()
    try:
        existing = {row.content for row in db.query(Question).all()}
        added = 0
        for subject, grade, content, answer, explanation, options in QUESTIONS:
            if content in existing:
                continue
            db.add(
                Question(
                    subject=subject,
                    grade=grade,
                    content=content,
                    answer=answer,
                    explanation=explanation,
                    options=json.dumps(options, ensure_ascii=False),
                )
            )
            existing.add(content)
            added += 1
        db.commit()
        if added:
            print(f"[seed] added {added} questions, total {len(existing)}")
    finally:
        db.close()
